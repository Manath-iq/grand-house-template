/**
 * Единственное место в проекте, где есть хексы.
 *
 * Если хекс появился в компоненте — это ошибка: перенос сайта на боевой домен
 * и правка фирменного цвета перестают быть операцией на одну строчку.
 * Проверяется грепом перед сдачей (см. README).
 *
 * Светлый премиум-камень. Десатурированный тёплый офф-вайт вместо кремового,
 * один акцент только на действии. Кремовый фон с терракотой взят не был
 * сознательно: это самая узнаваемая пара в нише ИЖС, по ней сайт мгновенно
 * опознаётся как шаблон.
 *
 * Акцент — зелёный с фирменного знака компании, а не выбранный на вкус.
 * Тёплая каменная база под него не переделывалась: холодный офф-вайт с
 * зеленью даёт больничную пару, а тёплый — приглушённую и дорогую.
 *
 * Все пары «текст / фон» проверены на 4.5:1, включая три светлые поверхности
 * подряд — вспомогательный текст на самой тёмной из них даёт 4.70:1.
 */
export const palette = {
  /** Основной фон, ~70% страницы. */
  paper: '#F6F4F0',
  /** Карточки, полосы-передышки, инпуты. */
  paperSoft: '#EDE9E3',
  /** Третий уровень: неактивный фильтр, подложка таблицы, зебра. */
  paperDeep: '#E3DED6',

  /** Текст и фон тёмной секции «как мы строим». */
  ink: '#171614',
  /** Поднятые поверхности внутри тёмной секции. */
  inkSoft: '#232120',
  /** Самый глубокий тон: футер. */
  inkDeep: '#0F0E0D',

  /** Вспомогательный текст на светлом. */
  muted: '#655F59',
  /** Вспомогательный текст на тёмном. */
  mutedOnInk: '#9A948B',

  /**
   * Фирменная зелень со знака Grand House.
   *
   * Один и тот же тон работает и заливкой, и текстом: 5.96:1 как текст на
   * самой тёмной светлой поверхности и 7.26:1 для светлого текста на заливке.
   * Держать один акцент вместо пары «акцент + акцент-для-текста» дешевле
   * в поддержке и строже выглядит.
   */
  accent: '#2E5A36',
  /** Тот же акцент, осветлённый для текста в тёмной секции: 7.18:1 на ink. */
  accentOnInk: '#8CB894',
} as const;

/**
 * Собирает строку для инлайна в <html style="…">.
 *
 * Отдаём только неизменяемую базу с префиксом --c-. Смысловые токены
 * (--fg, --bg, --surface, --line) собираются из неё в tokens.css.
 *
 * Разделение не косметическое: тёмная секция меняет роли --fg и --bg местами,
 * и если бы обмен шёл между самими смысловыми переменными, он бы схлопнулся —
 * внутри одного правила var() читает уже новое значение соседней переменной.
 */
export function paletteToCssVars(): string {
  return Object.entries(palette)
    .map(([key, value]) => `--c-${key.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase())}:${value}`)
    .join(';');
}
